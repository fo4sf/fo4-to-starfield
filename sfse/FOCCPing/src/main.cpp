// FOCCPing: the B0 spike (docs/combined-core-cpp-port.md section 4; the owner's call of 28 Oct 2026: stack A first,
// fixed where 1.16.244 breaks it). One Papyrus native, FOCC.Ping(int v) -> v + 1, declared by
// scripts/combined_probes/FOCC.psc and called by FOCC_B0.Ping. It settles whether a value crosses from a quest script
// into our SFSE plugin and back on runtime 1.16.244, the link the C++ port stands on; the plugin keeps no state.
//
// Built against libxse/commonlibsf 9d090c4 (the original CommonLibSF is archived and points there). Checked offline:
//   - The Address Library for 1.16.244 (v22) is format 5. libxse's REL::IDDB reads formats 1, 2 and 5
//     (lib/commonlib-shared/src/REL/IDDB.cpp) from Data\SFSE\Plugins\versionlib-1-16-244-0.bin, on the first id
//     lookup; a missing or mismatched file is REX::FAIL, a message box, and the game stops.
//   - libxse has no SFSE::SetPapyrusCallback. The native is bound when SFSE sends kPostDataLoad (all game data
//     loaded; the script VM exists by then): RE::GameVM::GetSingleton() (ID::GameVM::Singleton, an id of the
//     1.15.216+ space) -> GetVM() -> IVirtualMachine::BindNativeMethod. FOCC.pex is linked when the console first
//     calls FOCC_B0.Ping, long after, so the native is in the VM's table by then. No hook, no trampoline, no
//     address of our own.
//   - A global native takes std::monostate in the self slot (RE/B/BSScriptUtil.h). BindNativeMethod's last two
//     arguments: callable from tasklets (true), latent (false).
//   - The version data (SFSEPlugin_Version) is generated by the commonlibsf.plugin rule from xmake.lua: the
//     AddressLibraryV2 bit (the one SFSE 0.2.21's PluginManager counts as address independence), the 1.14.70+
//     layout, CompatibleVersions RUNTIME_LATEST.
// The kit's rule: a dll that keeps the game from the main menu is deleted at once (runbook section B0).

#include "pch.h"

namespace
{
	using namespace std::string_view_literals;

	// FOCC.psc: `int Function Ping(int v) global native`
	std::int32_t Ping(std::monostate, std::int32_t a_v)
	{
		REX::INFO("ping {} -> {}", a_v, a_v + 1);
		return a_v + 1;
	}

	void BindPing()
	{
		const auto game = RE::GameVM::GetSingleton();
		const auto vm = game ? game->GetVM() : nullptr;
		if (!vm) {
			REX::ERROR("no script VM at PostDataLoad: FOCC.Ping not bound");
			return;
		}
		vm->BindNativeMethod("FOCC"sv, "Ping"sv, &Ping, true, false);
		REX::INFO("bound FOCC.Ping");
	}

	void OnMessage(SFSE::MessagingInterface::Message* a_msg)
	{
		if (a_msg && a_msg->type == SFSE::MessagingInterface::kPostDataLoad) {
			BindPing();
		}
	}
}

SFSE_PLUGIN_LOAD(const SFSE::LoadInterface* a_sfse)
{
	SFSE::Init(a_sfse, { .trampoline = false, .hook = false });
	REX::INFO("FOCCPing loaded on runtime {}", a_sfse->RuntimeVersion().string());

	// true either way: a dll that stays loaded and binds nothing leaves `got=0` and this log line, the finding the
	// runbook's B0-2 card reads; false would make SFSE drop the plugin with less to read
	const auto messaging = SFSE::GetMessagingInterface();
	if (!messaging || !messaging->RegisterListener(&OnMessage)) {
		REX::ERROR("no SFSE messaging interface: FOCC.Ping not bound");
		return true;
	}
	REX::INFO("listening for PostDataLoad; FOCC.Ping binds then");
	return true;
}
